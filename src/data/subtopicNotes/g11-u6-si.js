          content: "### ප්‍රධාන අන්තරාසර්ග ග්‍රන්ථි සහ හෝමෝන:\n1. **පිටියුටරි ග්‍රන්ථිය** (මොළය පාමුල ප්‍රධාන ග්‍රන්ථිය): වර්ධක හෝමෝනය (GH), තයිරොයිඩ් උත්තේජක හෝමෝනය (TSH), ප්‍රතිමුත්‍රල හෝමෝනය (ADH - වෘක්ක නාලිකාවල ජල ප්‍රතිඅවශෝෂණය පාලනය කරයි).\n2. **තයිරොයිඩ් ග්‍රන්ථිය** (බෙල්ලේ පිහිටයි): **තයිරොක්සින්** (මූලික පරිවෘත්තීය සීඝ්‍රතාව පාලනය කරයි; ළමා වියේ ඌනතාවයෙන් ක්‍රෙටීනතාවද, වැඩිහිටි වියේදී මික්සඩීමාවද, අයඩින් ඌනතාවයෙන් ගලගණ්ඩයද ඇතිවේ).\n3. **අග්න්‍යාශය (ලැන්ගර්හැන්ස් දීපිකා)**:\n   - **බීටා සෛල**: **ඉන්සියුලින්** ස්‍රාවය කරයි.\n   - **ඇල්ෆා සෛල**: **ග්ලුකොගන්** ස්‍රාවය කරයි.\n4. **අධිවෘක්ක ග්‍රන්ථි**: **ඇඩ්‍රිනලින්** (හදිසි අවස්ථාවල සටනට හෝ පලායාමට සිරුර සූදානම් කරයි: හෘද ස්පන්දනය වැඩි කරයි, රුධිර පීඩනය හා ග්ලූකෝස් නංවයි).\n\n### රුධිර ග්ලූකෝස් සමස්ථිතිය (සාමාන්‍ය අගය ~70-110 mg/dL):\n- **ආහාර ගැනීමෙන් පසු රුධිර ග්ලූකෝස් වැඩි වූ විට**:\n  - අග්න්‍යාශයේ බීටා සෛල උත්තේජනය වී **ඉන්සියුලින්** රුධිරයට නිකුත් කරයි.\n  - ඉන්සියුලින් මඟින් අක්මාව සහ පේශි සෛල තුළ ග්ලූකෝස් **ග්ලයිකොජන්** බවට හරවා තැන්පත් කරවයි.\n  - සෛල තුළ ග්ලූකෝස් දහනය වේගවත් කර සාමාන්‍ය මට්ටමට අඩු කරයි.\n- **නිරාහාරව සිටීමේදී රුධිර ග්ලූකෝස් අඩු වූ විට**:\n  - ඇල්ෆා සෛල මඟින් **ග්ලුකොගන්** නිකුත් කරයි.\n  - ග්ලුකොගන් මඟින් අක්මාවේ ගබඩා කර ඇති ග්ලයිකොජන් නැවත ග්ලූකෝස් බවට බිඳහෙළා රුධිරයට මුදාහැර සාමාන්‍ය මට්ටමට නංවයි.\n- *අක්‍රමිකතා*: ඉන්සියුලින් ඌනතාවය නිසා **දියවැඩියාව (Diabetes Mellitus)** හටගනී.\n\n### දේහ උෂ්ණත්ව පාලනය (සාමාන්‍ය අගය ~37°C):\n- **සීතල පරිසරයකදී**: රුධිර වාහිනී සංකෝචනය (තාප විකිරණය අවම කරයි), වෙව්ලීම / ගැහීම (පේශි සංකෝචනයෙන් තාපය ජනනය කරයි), රෝම කෙළින් වීම.\n- **උණුසුම් පරිසරයකදී**: රුධිර වාහිනී විස්තාරණය (සමේ පෘෂ්ඨයට වැඩිපුර රුධිරය ගලා ගොස් තාපය විකිරණය කරයි), දහඩිය දැමීම (දහඩිය වාෂ්පීකරණයේ ගුප්ත තාපය උරාගෙන සිරුර සිසිල් කරයි)."
